// The two data contracts of a distillation harness (ADR-008, spec 009): the run record a harness is given and the skill set it returns, as zod
// definitions the TypeScript types derive from and the JSON Schema files under schemas/ are generated from. The run record holds only what the model
// and the world produced; it has no field for a score, a solver path, a goal role, a timing or a label of which calls were needed, so a harness cannot
// be given one. A breaking change is a new schema version, never an edit.
import { z } from "zod";

/** The pinned settings a run recorded for its model. */
export const settingsSchema = z.strictObject({
  temperature: z.number().nullable(),
  effort: z.string().nullable(),
  thinking: z.union([z.string(), z.number()]).nullable(),
});

export const callSchema = z.strictObject({
  id: z.string(),
  tool: z.string(),
  arguments: z.record(z.string(), z.unknown()),
  status: z.enum(["ok", "failed"]),
  /** The text the agent saw, regenerated by replaying the run. */
  output: z.string(),
  /** For a failed call, the world's own refusal. */
  refusal: z.string().optional(),
});

export const turnSchema = z.strictObject({
  text: z.string(),
  /** The reasoning the provider returned for this turn; absent when it returned none. */
  reasoning: z.string().optional(),
  calls: z.array(callSchema),
});

export const runRecordSchema = z.strictObject({
  /** Unique within a session. */
  id: z.string().min(1),
  /** The task prompt the agent received. */
  prompt: z.string(),
  models: z.strictObject({ requested: z.string().nullable(), resolved: z.array(z.string()) }),
  settings: settingsSchema.nullable(),
  /** Whether the tool-calling turns came with the provider's reasoning: all of them, some, or none; `not-kept` for a run that kept no conversation, whose turns are its calls alone. */
  reasoning: z.enum(["returned", "partial", "none", "not-kept"]),
  turns: z.array(turnSchema),
  finalAnswer: z.string(),
});
export type RunRecord = z.infer<typeof runRecordSchema>;

export const skillSchema = z.strictObject({
  name: z.string().regex(/^[a-z0-9]+(-[a-z0-9]+)*$/),
  description: z.string().min(1),
  /** `SKILL.md` with its front matter, and optional references; relative paths, UTF-8 text. */
  files: z.array(z.strictObject({ path: z.string().min(1), content: z.string() })).min(1),
  tags: z.array(z.string()).optional(),
  /** Which runs, and which calls of them, the skill was derived from. */
  evidence: z.array(z.strictObject({ run: z.string(), call: z.number().int().optional() })).optional(),
});
export type Skill = z.infer<typeof skillSchema>;

/** A non-empty list of skills; a list of one is an ordinary result. */
export const skillSetSchema = z.strictObject({ skills: z.array(skillSchema).min(1) });
export type SkillSet = z.infer<typeof skillSetSchema>;

const tokensSchema = z.strictObject({ input: z.number().nullable(), output: z.number().nullable(), cacheRead: z.number().nullable(), cacheCreation: z.number().nullable() });

export const stageSchema = z.strictObject({
  stage: z.string(),
  durationMs: z.number(),
  tokens: tokensSchema.nullable(),
  /** Null, never zero, when the stage has no price. */
  costUsd: z.number().nullable(),
  model: z.strictObject({ requested: z.string(), resolved: z.string().nullable() }).optional(),
});
export type Stage = z.infer<typeof stageSchema>;

const priceQuoteSchema = z.strictObject({
  source: z.enum(["pin", "market-quote"]),
  openRouterId: z.string().nullable(),
  fetchedAt: z.string().nullable(),
  perMillion: z.strictObject({ input: z.number(), output: z.number(), cacheRead: z.number().optional(), cacheWrite: z.number().optional() }),
  note: z.string().optional(),
});

/** What a harness says about itself (`describe()`): hashes, settings, identifiers and fixed codes, never recorded text. */
export const provenanceSchema = z.strictObject({
  harness: z.strictObject({ name: z.string(), processVersion: z.string() }),
  /** Each model call the harness makes, by role (a critic, a reviser, a distiller). */
  roles: z.record(z.string(), z.strictObject({ requested: z.string(), resolved: z.array(z.string()), settings: settingsSchema.nullable(), price: priceQuoteSchema.nullable() })),
  prompts: z.record(z.string(), z.strictObject({ version: z.string(), sha256: z.string() })),
  /** An external service's own account of its version, or why that is not known. */
  service: z.union([z.strictObject({ name: z.string(), version: z.string(), released: z.string(), commit: z.string(), environment: z.string() }), z.strictObject({ name: z.string(), unknown: z.string() })]).nullable(),
  /** True when run records are kept in a third-party store; such a harness runs only with an explicit operator option. */
  retainedExternally: z.boolean(),
  stages: z.array(stageSchema),
  spend: z.strictObject({ costUsd: z.number().nullable(), pricedStages: z.number().int(), unpricedStages: z.number().int(), tokens: tokensSchema }),
  /** For a harness that reviews its own output: the rounds and verdicts, hashes and values only. */
  review: z.strictObject({ rounds: z.array(z.strictObject({ n: z.number().int(), skillSha256: z.string(), overall: z.enum(["accept", "revise", "reject"]) })), outcome: z.enum(["accept", "reject"]) }).optional(),
});
export type Provenance = z.infer<typeof provenanceSchema>;

/** The JSON Schema of a definition, with sorted keys so the committed file is stable. */
export function jsonSchemaOf(schema: z.ZodType): unknown {
  const sort = (v: unknown): unknown => {
    if (Array.isArray(v)) return v.map(sort);
    if (v !== null && typeof v === "object") {
      const o = v as Record<string, unknown>;
      return Object.fromEntries(Object.keys(o).sort().map((k) => [k, sort(o[k])]));
    }
    return v;
  };
  return sort(z.toJSONSchema(schema));
}

/** What the command writes about a distillation (`harness.json`): the harness's provenance, each recorded run by hash, each skill by hash and the outcome. */
export const distillationRecordSchema = provenanceSchema.extend({
  runs: z.array(z.strictObject({ id: z.string(), runLogSha256: z.string(), scoreSha256: z.string(), models: z.array(z.string()), settings: settingsSchema.nullable() })),
  skills: z.array(z.strictObject({ name: z.string(), sha256: z.string() })),
  /** How the runs were recorded to the harness: with the model's turns (`conversation`), as calls alone (`placeholder`), or both (`mixed`). Absent when none were recorded. */
  recordingFormat: z.enum(["conversation", "placeholder", "mixed"]).nullable().optional(),
  /** The code that ran: its commit, whether the tree had changes and a hash of them (null when git could not say). */
  code: z.strictObject({ commit: z.string().nullable(), dirty: z.boolean().nullable(), changesSha256: z.string().nullable() }).nullable(),
  /** `skill-set`, or the refusal's code. */
  outcome: z.string(),
  /** Fixed text: never anything a model wrote. */
  reason: z.string(),
});
export type DistillationRecord = z.infer<typeof distillationRecordSchema>;
